<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

class QuizAnswer extends Model
{
    protected $fillable = [
        /*
        |--------------------------------------------------------------------------
        | RELATION
        |--------------------------------------------------------------------------
        */

        'quiz_attempt_id',

        'question_id',

        /*
        |--------------------------------------------------------------------------
        | LEGACY ANSWER
        |--------------------------------------------------------------------------
        |
        | Sistem lama memakai QuestionOption.
        |
        | Jangan dipakai untuk data quiz baru.
        |
        */

        'selected_option_id',

        /*
        |--------------------------------------------------------------------------
        | NEW MULTIPLE CHOICE
        |--------------------------------------------------------------------------
        |
        | Nilainya:
        |
        | A
        | B
        | C
        | D
        |
        */

        'selected_answer',

        /*
        |--------------------------------------------------------------------------
        | ESSAY
        |--------------------------------------------------------------------------
        */

        'answer_text',

        /*
        |--------------------------------------------------------------------------
        | SCORING
        |--------------------------------------------------------------------------
        */

        'is_correct',

        'points_awarded',

        /*
        |--------------------------------------------------------------------------
        | MANUAL ESSAY REVIEW
        |--------------------------------------------------------------------------
        */

        'manual_score',

        'reviewed_by',

        'reviewed_at',
    ];

    protected function casts(): array
    {
        return [
            /*
            |--------------------------------------------------------------------------
            | BOOLEAN
            |--------------------------------------------------------------------------
            */

            'is_correct' =>
                'boolean',

            /*
            |--------------------------------------------------------------------------
            | DECIMAL
            |--------------------------------------------------------------------------
            */

            'points_awarded' =>
                'decimal:2',

            'manual_score' =>
                'decimal:2',

            /*
            |--------------------------------------------------------------------------
            | DATE
            |--------------------------------------------------------------------------
            */

            'reviewed_at' =>
                'datetime',
        ];
    }

    /*
    |--------------------------------------------------------------------------
    | ATTEMPT
    |--------------------------------------------------------------------------
    */

    public function attempt(): BelongsTo
    {
        return $this->belongsTo(
            QuizAttempt::class,
            'quiz_attempt_id'
        );
    }

    /*
    |--------------------------------------------------------------------------
    | QUESTION
    |--------------------------------------------------------------------------
    */

    public function question(): BelongsTo
    {
        return $this->belongsTo(
            Question::class
        );
    }

    /*
    |--------------------------------------------------------------------------
    | LEGACY SELECTED OPTION
    |--------------------------------------------------------------------------
    |
    | Tetap ada sementara untuk historical data lama.
    |
    */

    public function selectedOption():
        BelongsTo
    {
        return $this->belongsTo(
            QuestionOption::class,
            'selected_option_id'
        );
    }

    /*
    |--------------------------------------------------------------------------
    | REVIEWER
    |--------------------------------------------------------------------------
    */

    public function reviewer(): BelongsTo
    {
        return $this->belongsTo(
            User::class,
            'reviewed_by'
        );
    }
}